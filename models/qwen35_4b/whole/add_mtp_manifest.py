#!/usr/bin/env python3
"""Add the MTP / 4-row-verify / draft-head roles to a qwen35 whole-model manifest.

The plain manifest is generated by tools/manifest/mkmanifest.py.  This script
keeps every existing role and appends params.mtp, kernels.decode.verify,
kernels.mtp.t1, kernels.mtp.prompt and kernels.lm_head.draft.
"""
from __future__ import annotations

import argparse
import json
import re
import sys


def parse_layout(path):
    packs, members = {}, []
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        p = line.split()
        if len(p) >= 4 and p[1] == "-":
            packs[p[0]] = int(p[3])
            continue
        m = {"name": p[0], "pack": p[1], "offset": int(p[2]), "bytes": int(p[3])}
        if len(p) > 4 and p[4] == "blk":
            m["strips"] = [int(p[5]), int(p[6]), int(p[7])]
        members.append(m)
    return packs, members


def member(m, kinds, mtp):
    d = {"name": m["name"], "pack": m["pack"], "offset": m["offset"], "bytes": m["bytes"]}
    if mtp:
        d.update(layer=0, param=m["name"], kind="mtp")
    else:
        j, param = m["name"][1:].split(".", 1)
        d.update(layer=int(j), param=param, kind="gdn" if kinds[int(j)] == "gdn" else "attn")
    if "strips" in m:
        d["strips"] = m["strips"]
    return d


def io_entry(e):
    return {"name": e[0], "bytes": e[1], "dtype": e[2], "shape": e[3]}


def kernel_io(io, name):
    key = name if name in io else name + ".axmodel"
    return [io_entry(e) for e in io[key]["in"]], [io_entry(e) for e in io[key]["out"]]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("base")
    ap.add_argument("out")
    ap.add_argument("io")
    ap.add_argument("--mtp-layout", required=True)
    ap.add_argument("--verify-layout", required=True)
    ap.add_argument("--verify-name", default="qwen35_9b_group16_verify4_m4_gggagggagggaggga_mx4_kvc_c16384_npu4")
    ap.add_argument("--mtp-t1", default="qwen35_9b_mtp_t1_mx4_kvc_c16384_npu4")
    ap.add_argument("--mtp-prompt", default="qwen35_9b_mtp_prefill256_mx4_kvc_c16384_npu4")
    ap.add_argument("--draft-name", default="mul_mat_mx4_n65536_k4096")
    args = ap.parse_args()

    man = json.load(open(args.base))
    io = json.load(open(args.io))
    attn = man["params"]["attn"]
    H = attn["ln1"]["shape"][0]
    F = attn["w_gate"]["shape"][0]
    D = attn["q_norm"]["shape"][0]
    HQ = attn["w_q"]["shape"][0] // (2 * D)
    HKV = attn["w_k"]["shape"][0] // D
    QD, KD = HQ * D, HKV * D

    tag = re.search(r"group\d+_([ga]+)_", man["kernels"]["decode.group"]["file"]).group(1)
    kinds = ["gdn" if c == "g" else "attn" for c in tag]

    mtp_packs, mtp_members = parse_layout(args.mtp_layout)
    ver_packs, ver_members = parse_layout(args.verify_layout)

    for name in (args.verify_name, args.mtp_t1, args.mtp_prompt, args.draft_name):
        if name + ".axmodel" not in io:
            sys.exit(f"{args.io}: no IO entry for {name}.axmodel")

    norms = {
        "ln_e": ("nextn.enorm.weight", H), "ln_h": ("nextn.hnorm.weight", H),
        "head_norm": ("nextn.shared_head_norm.weight", H),
        "ln1": ("attn_norm.weight", H), "ln2": ("post_attention_norm.weight", H),
        "q_norm": ("attn_q_norm.weight", D), "k_norm": ("attn_k_norm.weight", D),
    }
    weights = {
        "w_fc": ("nextn.eh_proj.weight", (H, 2 * H)),
        "w_q": ("attn_q.weight", (2 * QD, H)),
        "w_k": ("attn_k.weight", (KD, H)),
        "w_v": ("attn_v.weight", (KD, H)),
        "w_o": ("attn_output.weight", (H, QD)),
        "w_gate": ("ffn_gate.weight", (F, H)),
        "w_up": ("ffn_up.weight", (F, H)),
        "w_down": ("ffn_down.weight", (H, F)),
    }
    params = {}
    for n, (gguf, width) in norms.items():
        params[n] = {"gguf": gguf, "convert": "tensor", "bytes": 4 * width, "dtype": 3, "shape": [width]}
    for n, (gguf, (N, K)) in weights.items():
        assert N * K // 2 == next(m["bytes"] for m in mtp_members if m["name"] == n), n
        params[n] = {"gguf": gguf, "convert": "mxfp4", "bytes": N * K // 2, "dtype": 1 if n == "w_fc" else 15,
                     "shape": [N * K // 2] if n == "w_fc" else [N, K]}
        s = "s_" + n[2:]
        assert N * K // 32 == next(m["bytes"] for m in mtp_members if m["name"] == s), s
        params[s] = {"gguf": gguf, "convert": "mxfp4_scales", "bytes": N * K // 32, "dtype": 1,
                     "shape": [N * K // 32] if n == "w_fc" else [N, K // 32]}
    man["params"]["mtp"] = params

    def add_kernel(role, name, layouts):
        packs, members = layouts
        ins, outs = kernel_io(io, name)
        man["kernels"][role] = {"file": name + ".axmodel", "in": ins, "out": outs,
                                "packs": packs, "members": [member(m, kinds, role.startswith("mtp.")) for m in members]}

    add_kernel("decode.verify", args.verify_name, (ver_packs, ver_members))
    add_kernel("mtp.t1", args.mtp_t1, (mtp_packs, mtp_members))
    add_kernel("mtp.prompt", args.mtp_prompt, (mtp_packs, mtp_members))
    ins, outs = kernel_io(io, args.draft_name)
    man["kernels"]["lm_head.draft"] = {"file": args.draft_name + ".axmodel", "in": ins, "out": outs}

    with open(args.out, "w") as f:
        json.dump(man, f, indent=1)
        f.write("\n")
    print(f"wrote {args.out}: roles {', '.join(man['kernels'])}, H={H} F={F} D={D} HQ={HQ} HKV={HKV}")


if __name__ == "__main__":
    main()
